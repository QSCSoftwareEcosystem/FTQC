#include <system_error>

using namespace mlir;
using namespace mlir::ftqc;

//===----------------------------------------------------------------------===//
// IQSCppEmitter
//===----------------------------------------------------------------------===//

namespace {

class IQSCppEmitter {
public:
  IQSCppEmitter(bool withNoise, double t1, double t2, unsigned rngSeed)
      : withNoise(withNoise), t1(t1), t2(t2), rngSeed(rngSeed) {}

  std::string emitModule(ModuleOp mod) {
    emitPreamble();
    for (auto func : mod.getOps<func::FuncOp>()) {
      if (!func.isDeclaration())
        emitFunction(func);
    }
    emitMain();
    return os.str();
  }

private:
  bool     withNoise;
  double   t1, t2;
  unsigned rngSeed;

  std::string           buf;
  llvm::raw_string_ostream os{buf};

  // Per-function state, reset for each function.
  DenseMap<Value, int>  qubitIdx;
  DenseMap<Value, int>  measureIdx;
  int                   nextQubit   = 0;
  int                   nextMeasure = 0;
  // Store per-function info for emitMain.
  struct FuncInfo { std::string name; int nqubits; int nmeasure; };
  SmallVector<FuncInfo> funcs;

  void resetPerFunc() {
    qubitIdx.clear();
    measureIdx.clear();
    nextQubit   = 0;
    nextMeasure = 0;
  }

  int qid(Value v) {
    auto it = qubitIdx.find(v);
    return it != qubitIdx.end() ? it->second : -1;
  }
  void setQ(Value v, int id) { qubitIdx[v] = id; }
  void propagateQ(Value dst, Value src) {
    auto it = qubitIdx.find(src);
    if (it != qubitIdx.end()) qubitIdx[dst] = it->second;
  }

  // ── Preamble ────────────────────────────────────────────────────────────

  void emitPreamble() {
    os << "// Generated by ftqc-opt --ftqc-lower-to-iqs-cpp\n"
       << "// Compile:\n"
       << "//   g++ -std=c++17 -I${IQS_ROOT}/include out.cpp \\\n"
       << "//       -L${IQS_ROOT}/build/lib -lintelqs_lib -lm -o sim\n"
       << "// Run:  ./sim [shots=1]\n"
       << "\n"
       << "#include \"qureg.hpp\"\n";
    if (withNoise)
      os << "#include \"NoisyQureg.hpp\"\n";
    os << "#include <cstdio>\n"
       << "#include <cstdlib>\n"
       << "#include <random>\n"
       << "#include <cmath>\n"
       << "\n"
       << "static std::mt19937_64 rng(" << rngSeed << ");\n"
       << "\n";

    // S-gate matrix: diag(1, i)
    os << "static TM2x2<ComplexDP> S_mat() {\n"
       << "    TM2x2<ComplexDP> G;\n"
       << "    G(0,0)={1,0}; G(0,1)={0,0};\n"
       << "    G(1,0)={0,0}; G(1,1)={0,1};\n"
       << "    return G;\n"
       << "}\n\n";

    // Measurement helper (with optional noise before collapse)
    if (withNoise) {
      os << "static int iqs_measure(iqs::NoisyQureg<ComplexDP> &psi, int q) {\n";
    } else {
      os << "static int iqs_measure(iqs::QubitRegister<ComplexDP> &psi, int q) {\n";
    }
    os << "    double p1 = psi.GetProbability((unsigned)q);\n"
       << "    std::uniform_real_distribution<double> d(0.0, 1.0);\n"
       << "    int out = (d(rng) < p1) ? 1 : 0;\n"
       << "    psi.CollapseQubit((unsigned)q, out == 1);\n"
       << "    psi.Normalize();\n"
       << "    return out;\n"
       << "}\n\n";
  }

  // ── Per-function emission ──────────────────────────────────────────────

  void emitFunction(func::FuncOp func) {
    resetPerFunc();

    // Count qubits by scanning InitZero/InitPlus and function arguments.
    // We also need the qubit index for function arguments (rare for top-level
    // circuits, but handle it for completeness).
    for (auto [i, arg] : llvm::enumerate(func.getArguments()))
      if (isa<LogicalQubitType>(arg.getType()))
        setQ(arg, nextQubit++);

    // Pre-scan to count total qubits.
    if (!func.empty()) {
      for (auto &op : func.getBody().front()) {
        if (isa<InitZeroOp, InitPlusOp>(&op))
          ++nextQubit;
      }
    }
    int nqubits = nextQubit;
    nextQubit = (int)func.getArguments().size(); // reset to assign in order

    std::string fname = func.getName().str();
    os << "static void run_" << fname << "(int shots) {\n";

    if (withNoise) {
      os << "    const double T1 = " << t1 << ", T2 = " << t2 << ";\n"
         << "    const unsigned RNG_SEED = " << rngSeed << ";\n";
    }

    // NoisyQureg must be allocated once (MPI state inside); reset per shot.
    if (withNoise) {
      os << "    iqs::NoisyQureg<ComplexDP> psi("
         << nqubits << ", RNG_SEED, T1, T2);\n";
    }

    os << "    for (int shot = 0; shot < shots; ++shot) {\n";

    if (withNoise) {
      os << "        psi.Initialize(\"base\", 0);\n"
         << "        psi.ResetTimeForAllQubits();\n";
    } else {
      os << "        iqs::QubitRegister<ComplexDP> psi("
         << nqubits << ", \"base\", 0);\n";
    }

    int measureCount = 0;
    if (!func.empty()) {
      for (auto &op : func.getBody().front())
        measureCount += (int)isa<LogicalMeasureOp>(&op);
    }

    if (measureCount > 0)
      os << "        int measurements[" << measureCount << "] = {};\n";

    nextMeasure = 0;
    if (!func.empty()) {
      for (auto &op : func.getBody().front())
        emitOp(&op);
    }

    if (withNoise)
      os << "        psi.ApplyNoiseGatesOnAllQubits();\n";

    // Print shot result.
    os << "        printf(\"shot %d:\", shot);\n";
    for (int i = 0; i < measureCount; ++i)
      os << "        printf(\" %d\", measurements[" << i << "]);\n";
    os << "        printf(\"\\n\");\n";

    os << "    } // end shots\n"
       << "}\n\n";

    funcs.push_back({fname, nqubits, measureCount});
  }

  // ── Op emission ───────────────────────────────────────────────────────

  void noise(int) {
    // NoisyQureg auto-injects noise inside each overridden Apply* method.
    // Explicit ApplyNoiseGate() calls are not needed (and would crash because
    // the base-class QubitRegister::ApplyNoiseGate requires rng_ptr_ to be
    // set via SetNoiseTimescales, which NoisyQureg does not call).
  }

  void emitOp(Operation *op) {
    llvm::TypeSwitch<Operation *>(op)

      // ── Qubit lifecycle ──────────────────────────────────────────────
      .Case<InitZeroOp>([&](InitZeroOp o) {
        int id = nextQubit++;
        setQ(o.getResult(), id);
        os << "        // q" << id << " = |0⟩  (from base init)\n";
      })
      .Case<InitPlusOp>([&](InitPlusOp o) {
        int id = nextQubit++;
        setQ(o.getResult(), id);
        os << "        psi.ApplyHadamard(" << id << ");";
        os << "  // q" << id << " = |+⟩\n";
        noise(id);
      })
      .Case<DeallocOp>([&](DeallocOp) {})

      // ── Single-qubit Clifford ────────────────────────────────────────
      .Case<LogicalHOp>([&](LogicalHOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        psi.ApplyHadamard(" << q << ");\n"; noise(q);
      })
      .Case<LogicalXOp>([&](LogicalXOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        psi.ApplyPauliX(" << q << ");\n"; noise(q);
      })
      .Case<LogicalYOp>([&](LogicalYOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        psi.ApplyPauliY(" << q << ");\n"; noise(q);
      })
      .Case<LogicalZOp>([&](LogicalZOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        psi.ApplyPauliZ(" << q << ");\n"; noise(q);
      })
      .Case<LogicalSOp>([&](LogicalSOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        { auto s = S_mat(); psi.Apply1QubitGate("
           << q << ", s); }\n"; noise(q);
      })

      // ── T gate / magic states ────────────────────────────────────────
      .Case<PrepareMagicTOp>([&](PrepareMagicTOp o) {
        // Magic-state qubit: consume silently in LogicalTOp.
        setQ(o.getResult(), -1);
      })
      .Case<PrepareMagicCCZOp>([&](PrepareMagicCCZOp o) {
        setQ(o.getResult(), -1);
      })
      .Case<LogicalTOp>([&](LogicalTOp o) {
        int q = qid(o.getQubit()); propagateQ(o.getResult(), o.getQubit());
        os << "        psi.ApplyT(" << q << ");\n"; noise(q);
      })

      // ── Two-qubit gates ──────────────────────────────────────────────
      .Case<LogicalCNOTOp>([&](LogicalCNOTOp o) {
        int c = qid(o.getControl()), t = qid(o.getTarget());
        propagateQ(o.getControlOut(), o.getControl());
        propagateQ(o.getTargetOut(),  o.getTarget());
        os << "        psi.ApplyCPauliX(" << c << ", " << t << ");\n";
        noise(c); noise(t);
      })
      .Case<LogicalCZOp>([&](LogicalCZOp o) {
        int a = qid(o.getQubit0()), b = qid(o.getQubit1());
        propagateQ(o.getResult0(), o.getQubit0());
        propagateQ(o.getResult1(), o.getQubit1());
        os << "        psi.ApplyCPauliZ(" << a << ", " << b << ");\n";
        noise(a); noise(b);
      })
      .Case<LogicalToffoliOp>([&](LogicalToffoliOp o) {
        int c0 = qid(o.getCtrl0()), c1 = qid(o.getCtrl1()),
            t  = qid(o.getTarget());
        propagateQ(o.getOutCtrl0(), o.getCtrl0());
        propagateQ(o.getOutCtrl1(), o.getCtrl1());
        propagateQ(o.getOutTarget(), o.getTarget());
        os << "        psi.ApplyToffoli(" << c0 << ", " << c1
           << ", " << t << ");\n";
        noise(c0); noise(c1); noise(t);
      })
      // ── Measurement ───────────────────────────────────────────────────
      .Case<LogicalMeasureOp>([&](LogicalMeasureOp o) {
        int q  = qid(o.getLogicalQubit());
        int mi = nextMeasure++;
        os << "        measurements[" << mi
           << "] = iqs_measure(psi, " << q << ");\n";
      })

      // ── Syndrome / EC / Pauli-frame — pass-through stubs ────────────
      .Case<SteaneXSyndromeOp>([&](SteaneXSyndromeOp o) {
        propagateQ(o.getOutLogicalQubit(), o.getLogicalQubit());
        os << "        // steane_x_syndrome (ideal stub)\n";
      })
      .Case<SteaneZSyndromeOp>([&](SteaneZSyndromeOp o) {
        propagateQ(o.getOutLogicalQubit(), o.getLogicalQubit());
        os << "        // steane_z_syndrome (ideal stub)\n";
      })
      .Case<ExtractSyndromeOp>([&](ExtractSyndromeOp o) {
        propagateQ(o.getOutLogicalQubit(), o.getLogicalQubit());
        os << "        // extract_syndrome (ideal stub)\n";
      })
      .Case<FlagSyndromeOp>([&](FlagSyndromeOp o) {
        propagateQ(o.getOutLogicalQubit(), o.getLogicalQubit());
        os << "        // flag_syndrome (ideal stub)\n";
      })
      .Case<ShorSyndromeOp>([&](ShorSyndromeOp o) {
        propagateQ(o.getOutLogicalQubit(), o.getLogicalQubit());
        os << "        // shor_syndrome (ideal stub)\n";
      })
      .Case<CorrectOp>([&](CorrectOp o) {
        propagateQ(o.getCorrectedQubit(), o.getLogicalQubit());
        os << "        // correct (ideal stub)\n";
      })
      .Case<ECRoundOp>([&](ECRoundOp o) {
        propagateQ(o.getCorrectedQubit(), o.getLogicalQubit());
        os << "        // ec_round (ideal stub)\n";
      })
      .Case<PauliFrameUpdateOp>([&](PauliFrameUpdateOp) {
        os << "        // pauli_frame_update\n";
      })
      .Case<CreateFrameOp>([&](CreateFrameOp) {})
      .Case<ApplyFrameOp>([&](ApplyFrameOp o) {
        for (auto [in, out] : llvm::zip(o.getQubits(), o.getOutQubits()))
          propagateQ(out, in);
      })

      // ── Distillation / encode / annotations — skip silently ─────────
      .Case<Distill15to1Op>([&](Distill15to1Op) {})
      .Case<Distill7to1Op>([&](Distill7to1Op) {})
      .Case<GateTeleportOp>([&](GateTeleportOp o) {
        propagateQ(o.getResult(), o.getQubit());
      })
      .Case<ResourceAnnotationOp>([&](ResourceAnnotationOp) {})
      .Case<EncodeOp>([&](EncodeOp) {})
      .Case<DecodeOp>([&](DecodeOp) {})
      .Case<func::ReturnOp>([&](func::ReturnOp) {})

      .Default([&](Operation *unknown) {
        os << "        // unsupported: "
           << unknown->getName().getStringRef() << "\n";
      });
  }

  // ── main() ────────────────────────────────────────────────────────────

  void emitMain() {
    os << "int main(int argc, char **argv) {\n"
       << "    iqs::mpi::Environment env(argc, argv);\n"
       << "    if (!env.IsUsefulRank()) return 0;\n"
       << "    int shots = (argc > 1) ? atoi(argv[1]) : 1;\n";
    for (auto &fi : funcs)
      os << "    run_" << fi.name << "(shots);\n";
    os << "    return 0;\n"
       << "}\n";
  }
};

} // namespace

//===----------------------------------------------------------------------===//
