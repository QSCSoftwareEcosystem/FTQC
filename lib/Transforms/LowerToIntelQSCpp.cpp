#define GEN_PASS_DEF_FTQCLOWERTOINTELQSCPPPASS
#include "FTQC/Transforms/Passes.h.inc"

#include "llvm/ADT/DenseMap.h"
#include "llvm/ADT/TypeSwitch.h"
