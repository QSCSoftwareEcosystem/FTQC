namespace {

struct FTQCLowerToIntelQSCppPassImpl
    : public ::impl::FTQCLowerToIntelQSCppPassBase<
          FTQCLowerToIntelQSCppPassImpl> {
  using FTQCLowerToIntelQSCppPassBase::FTQCLowerToIntelQSCppPassBase;

  void runOnOperation() override {
    auto mod = getOperation();

    IQSCppEmitter emitter(withNoise, t1Time, t2Time, rngSeed);
    std::string cpp = emitter.emitModule(mod);

    if (!outputFile.empty()) {
      std::error_code ec;
      llvm::raw_fd_ostream file(outputFile, ec);
      if (ec) {
        mod.emitError("ftqc-lower-to-iqs-cpp: cannot open '")
            << outputFile << "': " << ec.message();
        signalPassFailure();
        return;
      }
      file << cpp;
    } else {
      llvm::errs() << cpp;
    }

    // Attach as module attribute so FileCheck tests can inspect it.
    mod->setAttr("ftqc.iqs_cpp",
                 StringAttr::get(mod.getContext(), cpp));
  }
};

} // namespace

std::unique_ptr<mlir::Pass> mlir::ftqc::createLowerToIntelQSCppPass() {
  return std::make_unique<FTQCLowerToIntelQSCppPassImpl>();
}
