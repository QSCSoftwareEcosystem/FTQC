//===- LowerToIntelQSCpp.cpp - FTQC → Intel-QS C++ source emitter ---------===//
//
// Emits a standalone, compilable C++ source file that simulates the logical
// FTQC circuit using the Intel-QS (qHiPSTER) QubitRegister<ComplexDP> or
// NoisyQureg<ComplexDP> API.
//
// Compile the emitted file:
//   g++ -std=c++17 -I${IQS_ROOT}/include out.cpp \
//       -L${IQS_ROOT}/build/lib -lintelqs_lib -lm -o sim
//   ./sim [shots]
//
// Gate mapping:
//   ftqc.init_zero        → qubit index (initialised to |0⟩ by "base" ctor)
//   ftqc.init_plus        → qubit index + psi.ApplyHadamard()
//   ftqc.logical_h        → psi.ApplyHadamard(q)
//   ftqc.logical_x/y/z   → psi.ApplyPauliX/Y/Z(q)
//   ftqc.logical_s        → psi.Apply1QubitGate(q, S_mat)
//   ftqc.logical_t        → psi.ApplyT(q)
//   ftqc.logical_cnot     → psi.ApplyCPauliX(ctrl, tgt)
//   ftqc.logical_cz       → psi.ApplyCPauliZ(ctrl, tgt)
//   ftqc.logical_toffoli  → psi.ApplyToffoli(c0, c1, tgt)
//   ftqc.logical_measure  → Born-rule collapse + record result
//   syndrome / EC ops     → comment (ideal simulation stubs)
//===----------------------------------------------------------------------===//

#include "FTQC/Dialect/FTQCOps.h"
#include "FTQC/Dialect/FTQCTypes.h"
#include "FTQC/Transforms/Passes.h"

#include "mlir/Dialect/Func/IR/FuncOps.h"
